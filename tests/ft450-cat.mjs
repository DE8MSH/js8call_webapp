import assert from 'node:assert/strict';
import {parseFt450Frequency,ft450SetFrequency,ft450DialDisplay,Ft450CatSerial} from '../ft450-cat.js';
assert.equal(parseFt450Frequency('FA14250000;'),14250000);
assert.equal(parseFt450Frequency('FA07078000;'),7078000);
assert.equal(parseFt450Frequency('FA00030000;'),30000);
assert.equal(parseFt450Frequency('FB07078000;'),null);
assert.equal(parseFt450Frequency('FA60000001;'),null);
assert.equal(parseFt450Frequency('FA0707800;'),null);
assert.equal(ft450SetFrequency(7078000),'FA07078000;');
assert.equal(ft450SetFrequency(14250000),'FA14250000;');
assert.equal(ft450DialDisplay(7078000),'7.078 000');
assert.throws(()=>ft450SetFrequency(1));
assert.throws(()=>ft450SetFrequency(60000001));
const commands=[];
let unlocked=0;
const rig=new Ft450CatSerial(()=>{},()=>{});
rig.running=true;
rig.port={writable:{getWriter:()=>({write:async a=>{commands.push(new TextDecoder().decode(a));},releaseLock:()=>{unlocked++;}})}};
await rig.query();
await rig.setFrequency(7078000);
assert.deepEqual(commands,['FA;','FA07078000;']);
assert.equal(unlocked,2);
await assert.rejects(()=>rig.send('TX1;'));
console.log('FT-450 read-only CAT protocol and explicit FA write tests passed');
